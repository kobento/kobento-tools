// Bundles the compiled converter (build/Parser.js and the modules it requires) into one script
// for a browser or a WebView, build/json2rc-browser.js: it defines globalThis.json2rc, the
// Parser module's exports (convert, convertWithSymbols, ...). The Android app runs it to convert
// a document for its screen's density when it puts one on the home screen.
// Usage: node tools/bundle-browser.cjs   (build.sh runs it)
const fs = require("fs"), path = require("path");
const dir = path.join(__dirname, "..", "build");
const modules = new Map();
const visit = (name) => {
    if (modules.has(name)) return;
    const src = fs.readFileSync(path.join(dir, `${name}.js`), "utf8");
    modules.set(name, src);
    for (const m of src.matchAll(/require\("([^"]+)"\)/g)) {
        if (!m[1].startsWith("./")) throw new Error(`${name}.js requires ${m[1]}: not bundled for the browser`);
        visit(m[1].slice(2));
    }
};
visit("Parser");
const parts = [...modules].map(([name, src]) => `${JSON.stringify(name)}: function (module, exports, require) {\n${src}\n}`);
const out = `// Generated by tools/bundle-browser.cjs from build/: do not edit.
(function () {
"use strict";
var defs = {
${parts.join(",\n")}
};
var cache = {};
function load(name) {
    if (cache[name]) return cache[name].exports;
    var module = { exports: {} };
    cache[name] = module;
    defs[name](module, module.exports, function (p) { return load(p.replace(/^\\.\\//, "")); });
    return module.exports;
}
globalThis.json2rc = load("Parser");
})();
`;
fs.writeFileSync(path.join(dir, "json2rc-browser.js"), out);
console.log(`bundled ${modules.size} modules -> build/json2rc-browser.js (${out.length} B)`);
